@app.post("/chat/stream")
async def chat_stream(req: ChatRequest):
    """通过 SSE 返回处理进度、模型正文增量和最终完整结果。"""
    if _orchestrator is None or _memory is None:
        raise HTTPException(503, "服务未就绪")

    async def event_stream():
        event_queue: asyncio.Queue[Tuple[str, Dict[str, Any]]] = asyncio.Queue()
        sequence = 0

        async def enqueue_progress(event: Dict[str, Any]) -> None:
            await event_queue.put(("progress", event))

        async def enqueue_token(content: str) -> None:
            nonlocal sequence
            if not content:
                return
            sequence += 1
            await event_queue.put(("delta", {"text": content, "sequence": sequence}))

        process_task = asyncio.create_task(_process_chat(req, enqueue_progress, enqueue_token))
        queue_task = None
        try:
            while not (process_task.done() and event_queue.empty()):
                queue_task = asyncio.create_task(event_queue.get())
                done, _ = await asyncio.wait(
                    {process_task, queue_task},
                    timeout=15,
                    return_when=asyncio.FIRST_COMPLETED,
                )
                if queue_task in done:
                    event_name, payload = queue_task.result()
                    yield _sse_event(event_name, payload)
                else:
                    queue_task.cancel()
                    await asyncio.gather(queue_task, return_exceptions=True)
                    if not process_task.done():
                        yield ": keep-alive\n\n"

            response = await process_task
            yield _sse_event("result", response.model_dump())
            yield _sse_event("done", {"status": "complete"})
        except asyncio.CancelledError:
            process_task.cancel()
            raise
        except HTTPException as exc:
            yield _sse_event("error", {"message": str(exc.detail), "status": exc.status_code})
        except Exception as exc:
            logger.exception("SSE 对话处理失败")
            yield _sse_event("error", {"message": str(exc), "status": 500})
        finally:
            if queue_task is not None and not queue_task.done():
                queue_task.cancel()
                await asyncio.gather(queue_task, return_exceptions=True)
            if not process_task.done():
                process_task.cancel()
            await asyncio.gather(process_task, return_exceptions=True)

    return StreamingResponse(
        event_stream(),
        media_type="text/event-stream",
        headers={
            "Cache-Control": "no-cache",
            "X-Accel-Buffering": "no",
        },
    )


